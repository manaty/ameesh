// Types of the API client, generated from docs/api/openapi-v1.json (L88).
//   node scripts/gen-api.mjs           writes src/api/schema.d.ts
//   node scripts/gen-api.mjs --check   fails if the committed file is stale
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const SPEC = new URL("../../docs/api/openapi-v1.json", import.meta.url);
const OUT = new URL("../src/api/schema.d.ts", import.meta.url);
const HEADER = "// SPDX-License-Identifier: AGPL-3.0-only\n"
  + "// GENERATED by ui/scripts/gen-api.mjs from docs/api/openapi-v1.json: do not edit.\n\n";

const spec = JSON.parse(await readFile(SPEC, "utf8"));
const text = HEADER + astToString(await openapiTS(spec, { alphabetize: true }));
if (process.argv.includes("--check")) {
  const committed = await readFile(OUT, "utf8").catch(() => "");
  if (committed !== text) {
    console.error("%s is stale: run `npm run gen` in ui/", fileURLToPath(OUT));
    process.exit(1);
  }
} else {
  await writeFile(OUT, text);
}
